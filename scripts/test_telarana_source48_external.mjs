import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const read=p=>fs.readFileSync(p,'utf8'),ctx={window:{},Set,Map,Number,String,Array,Math,document:null};
vm.runInNewContext(read('la-telarana/fuente-48-contexto-externo.js'),ctx);
vm.runInNewContext(read('la-telarana/source-filter.js'),ctx);
const f=ctx.window.IDEA_TELARANA_F48_EXTERNAL,filter=ctx.window.IdeaLabSourceFilters;
const ids=new Set(f.nodes.map(n=>n.id)),edgeIds=new Set(f.edges.map(e=>e.id));
assert.equal(f.nodes.length,24);assert.equal(f.edges.length,30);
assert.equal(ids.size,24);assert.equal(edgeIds.size,30);
assert(f.edges.every(e=>ids.has(e.a)&&ids.has(e.b)&&e.a!==e.b));
assert.equal(f.metadata.relatedCatalogOrder,48);
assert.equal(f.metadata.sourceOrder,null);
assert.equal(f.metadata.originalPdfFound,false);
assert.equal(f.metadata.editionIdentityConfirmed,false);
assert.equal(f.metadata.reviewComplete,false);
assert.match(f.metadata.reviewStage,/contexto_independiente/);
assert.equal(f.metadata.externalTextSources.length,3);
assert(f.nodes.every(n=>n.podcastNotes.length>0&&n.podcastNotes.every(x=>x.timeSec===null)));
assert(f.nodes.every(n=>n.podcastNotes.every(x=>x.status==='contraste_textual_externo_no_equivale_a_fuente_f48')));
assert(f.nodes.find(n=>n.id==='f48-contexto-externo').note.includes('no está en Drive'));
assert(f.nodes.find(n=>n.id==='f48-filebo').note.includes('no desarrolla el relato de Atlántida'));
assert(f.nodes.find(n=>n.id==='f48-9000-anos').note.includes('no fechar'));
assert(f.nodes.find(n=>n.id==='f51-critias').subtitle.includes('inconcluso'));
assert(f.edges.find(e=>e.id==='f48-hipotesis-mod-atlantida').claimStatus==='hipotesis_moderna_no_verificada');
assert.equal(filter.sourceForModule({key:'IDEA_TELARANA_F48_EXTERNAL'}),'extra:f48-external');
assert.equal(filter.sourceForModule({key:'IDEA_TELARANA_F49_CANDIDATE'}),'extra:f49-candidate');
const tracker=JSON.parse(read('la-telarana/progreso-fuentes.json')),row=tracker.sourceCatalog.entries.find(e=>e.order===48);
assert.equal(row.status,'pendiente');
assert.equal(row.analysisCoverage.percent,0,'No acreditar análisis del PDF no recuperado');
assert.equal(row.tracking.initiated,false);
assert.equal(row.originalUrl,'');assert.equal(row.sourceUrl,'');
assert.equal(row.supplementalResearch.identityWithOriginalConfirmed,false);
assert.equal(row.supplementalResearch.fullTextRead,false);
assert.equal(row.supplementalResearch.fullOriginalPdfAvailable,false);
assert.equal(row.supplementalResearch.editionCandidate.editionMatchesOriginal,false);
assert.equal(row.supplementalResearch.sourceLayer,'extra:f48-external');
assert.equal(row.supplementalResearch.externalContextEntities,f.nodes.length);
assert.equal(row.supplementalResearch.externalContextRelations,f.edges.length);
const h=JSON.parse(read('linea-historia/estudios-telarana.json'));
assert(!h.items.some(e=>e.investigation?.sourceOrder===48),'Prohibido datar como historia el relato mítico');
const index=read('la-telarana/index.html'),flow=read('.github/workflows/pages.yml');
assert(index.includes('fuente-48-contexto-externo.js?v=20261116-1'));
assert(index.includes('"key":"IDEA_TELARANA_F48_EXTERNAL"'));
assert(flow.includes('cp la-telarana/fuente-48-contexto-externo.js'));
assert(flow.includes('node scripts/test_telarana_source48_external.mjs'));
console.log('OK: F48 original al 0%; 24 nodos y 30 aristas solo en contexto externo, sin cronología ficticia');
