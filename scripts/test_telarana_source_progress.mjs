/* El inventario es seguimiento interno: nunca incluirlo en la web pública. */
import assert from "node:assert/strict";
import fs from "node:fs";
const feed=JSON.parse(fs.readFileSync("la-telarana/progreso-fuentes.json","utf8"));
const page=fs.readFileSync("la-telarana/index.html","utf8");
const workflow=fs.readFileSync(".github/workflows/pages.yml","utf8");
assert.equal(feed.originalCatalogTotal,33);
assert.equal(feed.total,34);
assert.equal(feed.counts.reviewedPublished,1);
assert.equal(feed.counts.inReview,1);
assert.equal(feed.counts.notStarted,32);
assert.equal(feed.reviewed.filter(x=>x.status==="revision_publicada"&&x.reviewComplete===true).length,1);
assert(feed.inReview.every(x=>x.reviewComplete===false));
assert(feed.pendingSources.some(x=>x.videoId==="j_5Tj0kIj2c"&&x.reviewComplete===false));
assert.equal(feed.inventory.notebooks.reduce((n,x)=>n+x.count,0),33);
assert(!page.includes('id="source-review-rows"'),"El inventario no debe aparecer en la web pública");
assert(!page.includes('id="source-review-fill"'),"No publicar el medidor de seguimiento interno");
assert(!page.includes('source-progress.js'),"No cargar el inventario en la página");
assert(!workflow.includes('cp la-telarana/progreso-fuentes.json dist/'),"No publicar el registro interno");
assert(!workflow.includes('cp la-telarana/source-progress.js dist/'),"No publicar el visor interno");
console.log("OK: 34 fuentes registradas internamente, 33 identificadas en NotebookLM; nada expuesto en Pages");
