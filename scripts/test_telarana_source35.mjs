import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const read=p=>fs.readFileSync(p,'utf8'),ctx={window:{}};
vm.runInNewContext(read('la-telarana/fuente-35-revision-inicial.js'),ctx);
const f=ctx.window.IDEA_TELARANA_F35_REVIEW, ids=new Set(f.nodes.map(n=>n.id));
assert.equal(ids.size,7);assert.equal(f.edges.length,8);
assert(f.edges.every(e=>ids.has(e.a)&&ids.has(e.b)&&e.a!==e.b));
assert(!f.metadata.audioVerified&&!f.metadata.timecodesAvailable&&!f.metadata.reviewComplete);
assert(f.nodes.flatMap(n=>n.podcastNotes).every(n=>n.timeSec===null));
assert(f.nodes.find(n=>n.id==='f35-mosadeq').podcastNotes.some(n=>n.text.includes('febrero de 1953')));
const hist=JSON.parse(read('linea-historia/estudios-telarana.json'));
for(const id of ['study-f35-mosaddeq-1953','study-f35-jcpoa-2015'])assert.equal(hist.items.filter(e=>e.id===id).length,1);
assert(read('linea-historia/timeline-v4.js').includes('"study-f35-jcpoa-2015":"a-28-13"'));
const entry=JSON.parse(read('la-telarana/progreso-fuentes.json')).sourceCatalog.entries.find(e=>e.order===35);
assert.equal(entry.analysisCoverage.signals.verifiedTimelineEvents,2);
assert(read('la-telarana/index.html').includes('fuente-35-revision-inicial.js'));
assert(read('.github/workflows/pages.yml').includes('cp la-telarana/fuente-35-revision-inicial.js'));
console.log('OK: F35 distingue cronología, procedencia y límites audiovisuales');
