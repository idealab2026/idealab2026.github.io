import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const read=p=>fs.readFileSync(p,'utf8'),ctx={window:{}};
vm.runInNewContext(read('la-telarana/fuente-55-exodo.js'),ctx);
const f=ctx.window.IDEA_TELARANA_F55_REVIEW;
const ids=new Set(f.nodes.map(n=>n.id));
assert.equal(f.metadata.reviewComplete,false);
assert.equal(f.metadata.audioVerified,false);
assert(f.nodes.flatMap(n=>n.podcastNotes).every(n=>n.timeSec===null));
assert(f.edges.every(e=>ids.has(e.a)&&ids.has(e.b)&&e.a!==e.b));
assert.match(f.nodes.find(n=>n.id==='f55-estela-merneptah').note,/No menciona a Moisés ni demuestra/);
assert.match(f.nodes.find(n=>n.id==='f55-moises').note,/ausencia de prueba no demuestra/);
assert.match(f.nodes.find(n=>n.id==='f55-beni-hasan').note,/no prueba/);
assert.equal(f.edges.find(e=>e.id==='f55-hicsos-exodo').confidence,'hipotesis');
assert(read('la-telarana/index.html').includes('fuente-55-exodo.js'));
assert(read('.github/workflows/pages.yml').includes('cp la-telarana/fuente-55-exodo.js'));
console.log('OK: F55 separa interpretación, evidencia arqueológica y relato');
