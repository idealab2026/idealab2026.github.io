assert(f.nodes.find(n=>n.id==='f55-avarispiramesse-yacimientos').note.includes('Qantir'));
assert(f.nodes.find(n=>n.id==='f55-papiro-sallier-i').note.includes('no es una carta original'));
assert(f.nodes.find(n=>n.id==='f55-tablilla-leyenda-sargon').note.includes('siglo VII'));
assert(f.nodes.find(n=>n.id==='f55-exodo-critica-fuentes').note.includes('no es una descripción definitiva'));
assert(f.edges.find(e=>e.id==='f55-estela-determinativo').claimStatus==='evidencia_epigrafica_israel_en_canaan_no_egipto');
assert(f.edges.find(e=>e.id==='f55-sallier-apofis').claimStatus==='personaje_historico_en_ficcion_posterior');
assert(f.edges.find(e=>e.id==='f55-hicsos-exodo').claimStatus==='hipotesis_atribuida');
const notes=f.nodes.flatMap(n=>n.podcastNotes||[]);
assert.equal(notes.filter(n=>n.transcriptSearch).length,17);
assert(notes.filter(n=>n.transcriptSearch).every(n=>Number.isInteger(n.transcriptCharOffset)&&n.transcriptCharOffset>=0));
assert(notes.every(n=>n.timeSec===null&&n.audioVerified===false),'Sin audio inventado ni marcas horarias');
const biographies=ctx.window.IDEA_TELARANA_BIOGRAPHIES.curated;
