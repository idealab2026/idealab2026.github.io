assert(!f.edges.some(e=>e.a==='f55-moises'&&['f55-merneptah','f55-apofis-hicso','f55-seqenenra-taa'].includes(e.b)||e.b==='f55-moises'&&['f55-merneptah','f55-apofis-hicso','f55-seqenenra-taa'].includes(e.a)));
