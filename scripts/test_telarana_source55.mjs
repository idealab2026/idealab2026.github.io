assert.equal(cat.analysisCoverage.signals.entities,26);assert.equal(cat.analysisCoverage.signals.relations,34);
assert.equal(cat.analysisCoverage.signals.biographies,10);assert.equal(cat.analysisCoverage.signals.independentChecks,13);
assert.equal(cat.analysisCoverage.percent,20,'El avance audiovisual no se inventa');
