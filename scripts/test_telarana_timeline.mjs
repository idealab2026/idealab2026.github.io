/* Integridad de los hitos fechados compartidos entre ambos proyectos. */
import assert from "node:assert/strict";
import fs from "node:fs";
import vm from "node:vm";
const history=JSON.parse(fs.readFileSync("linea-historia/data.json","utf8"));
const feed=JSON.parse(fs.readFileSync("linea-historia/estudios-telarana.json","utf8"));
const timeline=fs.readFileSync("linea-historia/timeline-v4.js","utf8");
const historyHTML=fs.readFileSync("linea-historia/index.html","utf8");
const graphHTML=fs.readFileSync("la-telarana/index.html","utf8");
const progress=JSON.parse(fs.readFileSync("la-telarana/progreso-fuentes.json","utf8"));
// Ejecutar el mismo filtro de producción, no solo comprobar que existe un regex en el archivo.
const start=timeline.indexOf("function valid(d){"),end=timeline.indexOf("function loadLocal(){",start);
assert(start>=0&&end>start,"No se encuentra el filtro de estudios");
const runtime={cats:["Eras geológicas","Acontecimientos","Personajes","Historia bíblica","Filosofía","Pontífices","Actualidad","Cine","Literatura"],GEO:["Europa","Asia","África","América","Oceanía","Antártida","Mundial"]};
vm.runInNewContext(timeline.slice(start,end)+"\nthis.validStudy=validStudy;",runtime);
assert(feed.items.every(e=>runtime.validStudy(e)),"El lector de producción rechaza estudios del catálogo");
assert(runtime.validStudy(feed.items.find(e=>e.id==='study-f33-sociedad-francfort-1810')),"F33 debe cargar en la cronología");
const ancient=history.items.find(e=>e.id==="h-CA37");
assert.equal(ancient.y,-12000,"El archivo histórico no se debe alterar");
const correction=runtime.correctKnownHistorical(ancient);
assert.equal(correction.y,-9600);assert.equal(correction.e,-8200);assert.equal(correction.id,ancient.id);
assert(correction.investigation.confirmedBy.url.includes("whc.unesco.org"));
assert(correction.d.includes("original"));
const example=feed.items[0];
assert(!runtime.validStudy({...example,id:'study-invalido'}));
assert(!runtime.validStudy({...example,investigation:{...example.investigation,status:'hipotesis'}}));
assert(runtime.validStudy({...example,investigation:{...example.investigation,date:'1810',datePrecision:'año'}}),"Las fechas anuales no deben precisar un mes inventado");
for(const [studyId,originalId] of Object.entries(runtime.studyCanonicalIds)){
 const original=history.items.find(e=>e.id===originalId),study=feed.items.find(e=>e.id===studyId);
 assert(original&&study,"Falta un extremo de la reconciliación histórica");
 const merged=runtime.mergeCanonicalStudy(original,study);
 assert(merged.id===original.id&&merged.c===original.c&&merged.studyAlias===study.id,
  "La reconciliación debe conservar la identidad y categoría originales");
 assert(merged.investigation===study.investigation&&merged.y===study.y,
  "La ficha canónica debe conservar el estudio y su fecha precisa");
}
assert(timeline.includes('studyAliases.get(requested)||requested'),"Los enlaces desde el grafo deben resolver el ID del estudio");
assert(Array.isArray(feed.items)&&feed.items.length>0,"El catálogo no puede estar vacío");
assert(feed.reviewProtocol&&feed.reviewProtocol.required.length>=5,"Faltan controles del protocolo documental");
const ids=new Set(history.items.map(x=>x.id));
const feedIds=new Set(),dedupKeys=new Set();
const bySource={};
const normal=s=>String(s||"").normalize("NFD").replace(/[\u0300-\u036f]/g,"").toLowerCase().replace(/[^a-z0-9]+/g," ").trim();
for(const e of feed.items){
 assert(!feedIds.has(e.id),"ID duplicado: "+e.id);
 assert(!ids.has(e.id),"ID ya presente en la línea histórica: "+e.id);
 assert(/^study-(?:v\d+|vf\d+|f\d+)-[a-z0-9-]+$/.test(e.id),"ID editorial sin prefijo de fuente");
 feedIds.add(e.id);
 const inv=e.investigation||{};
 assert(inv.status==="hecho_documentado","Solo se pueden publicar hechos contrastados");
 assert(/^\d{4}(?:-\d{2}(?:-\d{2})?)?$/.test(inv.date||""),"Fecha inválida");
 if(inv.datePrecision==="año")assert(/^\d{4}$/.test(inv.date),"No inventar mes o día para hitos anuales");
 const year=Number(inv.date.slice(0,4));
 assert(Math.floor(e.y)===year,"El año del eje no coincide con la fecha");
 assert(e.c==="Acontecimientos"||e.c==="Actualidad","Categoría histórica inválida");
 assert(e.d&&e.d.length>120,"Descripción insuficiente");
 assert(Array.isArray(e.g)&&e.g.every(v=>["Europa","Asia","África","América","Oceanía","Antártida","Mundial"].includes(v)),"Geografía inválida");
 assert(inv.confirmedBy&&/^https:\/\//.test(inv.confirmedBy.url),"Falta fuente contrastada externa");
 if(inv.sourceType==="pdf_document")assert(/^https:\/\/www\.whitehouse\.gov\/wp-content\/uploads\/2025\/12\/2025-National-Security-Strategy\.pdf$/.test(inv.sourceUrl),"Falta PDF institucional original");
 else assert(/^https:\/\/www\.youtube\.com\/watch\?v=/.test(inv.sourceUrl),"Falta episodio");
 assert(Array.isArray(inv.relatedTelarana)&&inv.relatedTelarana.length>=1,"Sin enlace a La Telaraña");
 assert(inv.methodologicalLimits&&inv.methodologicalLimits.length>=60,"Sin límites de la evidencia");
 const key=normal(e.t)+"|"+year;
 assert(!dedupKeys.has(key),"Evento repetido: "+key);
 dedupKeys.add(key);
 const sourceKey=inv.sourceOrder===null?"suplementaria":inv.sourceOrder;
 if(inv.sourceOrder===null)assert(inv.sourceCatalogStatus==="pendiente_de_reconciliar_con_inventario_33","Fuente sin numeración debe declarar su situación de catálogo");
 bySource[sourceKey]=(bySource[sourceKey]||0)+1;
}
assert.equal(bySource[1],5,"Carga histórica de la fuente 1");
assert.equal(bySource[2],8,"Ocho hitos contrastados de la fuente 02");
assert.equal(bySource[4],7,"Siete hitos de historia española de la fuente 04");
assert.equal(bySource[7],5,"Cinco hechos independientes documentados de la fuente 07");
assert.equal(bySource[8],2,"Archivo de 2022 y declaracion de culpabilidad Carvajal 2025, independientes del episodio F08");
assert.equal(bySource.suplementaria,7,"Siete hechos contrastados de fuente no numerada");
assert.equal(progress.timeline.committedVerifiedEvents,feed.items.length,"Progreso histórico inconsistente");
assert.equal(progress.timeline.fromSupplementalResearch,bySource.suplementaria,"La investigación suplementaria debe contabilizarse por separado");
assert.equal(progress.counts.reviewedPublished,3,"El cierre 18 y 21 es documental; el resto de fuentes continúa en revisión");
assert(timeline.includes('readJSON("./estudios-telarana.json")'),"El visor no consume el catálogo");
assert(timeline.includes("function showStudyNote("),"Faltan fichas documentales");
assert(timeline.includes("if(d&&d.investigation){showStudyNote(d);return}"),"La ficha documental debe prevalecer frente a Wikipedia");
assert(timeline.includes('get("evento")'),"El enlace directo a un acontecimiento no está implementado");
assert(graphHTML.includes('get("entidad")'),"Falta navegación a personas desde la cronología");
const contextSource=fs.readFileSync("la-telarana/investigacion-frattini-contexto.js","utf8");
const context=JSON.parse(contextSource.split("window.IDEA_TELARANA_FRATTINI_EXTERNAL = ")[1].trim().replace(/;$/,""));
assert(context.nodes.some(n=>n.id==="vf150-khaled-meshaal"),"Falta Khaled Mashal en el grafo");
assert(context.edges.length>=5&&context.edges.every(e=>e.confidence==="documentado"&&/^https:\/\//.test(e.source)),"Faltan vínculos sustentados por documentos");
assert(graphHTML.includes('investigacion-frattini-contexto.js?v='),"Falta cargar el contexto histórico");
const graphModules=/var modules=(\[[^\n]+\]);/.exec(graphHTML);
assert(graphModules,"Falta el registro de carga del grafo");
const registry=JSON.parse(graphModules[1]);
assert(registry.some(m=>m.key==="IDEA_TELARANA_FRATTINI_EXTERNAL"&&m.kind==="mergePodcastStudy"),"El contexto Frattini no está conectado al registro de carga");
assert(graphHTML.includes('mergePodcastStudy(doc)'),"El registro no ejecuta la fusión documental");
assert(graphHTML.includes('study-(?:v\\d+|vf\\d+|f\\d+)-'),"La Telaraña no admite las identidades de hitos documentales y fuentes recientes");
assert(historyHTML.includes("timeline-v4.js?v="),"No se actualizó la caché del visor");
console.log("OK: "+feed.items.length+" acontecimientos contrastados, sin duplicados ni alegaciones convertidas en hechos");
