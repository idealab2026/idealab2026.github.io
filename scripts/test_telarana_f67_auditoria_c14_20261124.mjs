import assert from "node:assert/strict";
import fs from "node:fs";
import vm from "node:vm";
const path="la-telarana/fuente-67-auditoria-c14-20261124.js";
const ctx={window:{}};vm.runInNewContext(fs.readFileSync(path,"utf8"),ctx,{timeout:4000});
const d=ctx.window.IDEA_TELARANA_F67_AUDITORIA_C14_20261124;
assert.equal(d.metadata.sourceOrder,67);
assert(!d.metadata.audioVerified&&!d.metadata.reviewComplete&&!d.metadata.timecodesAvailable);
const n=new Map(d.nodes.map(x=>[x.id,x])),e=new Map(d.edges.map(x=>[x.id,x]));
assert.equal(n.size,d.nodes.length);assert.equal(e.size,d.edges.length);
for(const r of d.edges){assert(n.has(r.a)&&n.has(r.b));assert(/^https:\/\//.test(r.source));}
const {groups,stats}=d.statisticalAudit;
const sum=a=>a.reduce((a,b)=>a+b,0),mean=a=>sum(a)/a.length;
const w=groups.map(x=>1/x.se**2),m=sum(groups.map((x,i)=>x.mean*w[i]))/sum(w),q=sum(groups.map((x,i)=>(x.mean-m)**2*w[i]));
const all=groups.flatMap(x=>x.measurements),gm=mean(all);
assert.equal(all.length,12);
const ssb=sum(groups.map(x=>x.measurements.length*(mean(x.measurements)-gm)**2)),ssw=sum(groups.map(x=>sum(x.measurements.map(v=>(v-mean(x.measurements))**2)))),F=(ssb/2)/(ssw/9);
const near=(a,b,t=1e-8)=>assert(Math.abs(a-b)<t);
near(m,stats.weightedMean);near(q,stats.chiSquare);near(Math.exp(-q/2),stats.chiSquareP);
near(F,stats.anovaF);near((9/(9+2*F))**4.5,stats.anovaP);
near(q,6.351829478592922);near(F,4.700819536642771);
assert(n.get("f67c-gradient").note.includes("no fue significativa"));
assert(n.get("f67c-foia").note.includes("No se ha obtenido"));
assert.equal(e.get("f67c-gradient-sample").confidence,"hipotesis");
assert.equal(e.get("f67c-foia-casa").claimStatus,"testimonio_textual_atribuido");
const html=fs.readFileSync("la-telarana/index.html","utf8"),wf=fs.readFileSync(".github/workflows/pages.yml","utf8");
assert(html.includes('src="./fuente-67-auditoria-c14-20261124.js'));
assert(html.includes("mergeNewEpisode(window.IDEA_TELARANA_F67_AUDITORIA_C14_20261124)"));
assert(wf.includes("cp "+path+" dist/"+path));
for(const r of [...d.nodes,...d.edges])assert(html.includes('"'+new URL(r.source).hostname+'"'));
console.log("OK F67: reproducción numérica de chi-cuadrado y ANOVA, límites de inferencia y fuentes.");
