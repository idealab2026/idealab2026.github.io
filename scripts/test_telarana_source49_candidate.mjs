import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const read=p=>fs.readFileSync(p,'utf8');
const context={window:{}};
vm.runInNewContext(read('la-telarana/fuente-49-candidato.js'),context);
const f=context.window.IDEA_TELARANA_F49_CANDIDATE;
const feed=JSON.parse(read('la-telarana/progreso-fuentes.json'));
const row=feed.sourceCatalog.entries.find(e=>e.order===49);
assert.equal(f.metadata.reviewComplete,false);
assert.match(f.metadata.methodologicalNote,/sin prueba de identidad/);
assert.equal(row.analysisCoverage.percent,0);
assert.equal(row.supplementalResearch.identityWithOriginalConfirmed,false);
assert.equal(row.originalUrl,'');
assert(f.nodes.some(n=>n.id==='f49-candidato'&&n.note.includes('no sabemos si se trata del mismo recurso')));
assert(f.nodes.some(n=>n.id==='f49-pelasgos'&&n.note.includes('no se presenta como hecho')));
const ids=new Set(f.nodes.map(n=>n.id));
assert(f.edges.every(e=>ids.has(e.a)&&ids.has(e.b)&&e.a!==e.b));
assert(read('la-telarana/index.html').includes('fuente-49-candidato.js'));
assert(read('.github/workflows/pages.yml').includes('cp la-telarana/fuente-49-candidato.js'));
console.log('OK: candidato diferenciado de la F49 original y alegaciones contrastadas');
