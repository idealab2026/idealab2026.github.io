import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const read=p=>fs.readFileSync(p,'utf8'),context={window:{},Set,Map,Number,String,Array,Math,document:null};
vm.runInNewContext(read('la-telarana/fuente-49-candidato.js'),context);
vm.runInNewContext(read('la-telarana/source-filter.js'),context);
const f=context.window.IDEA_TELARANA_F49_CANDIDATE;
const feed=JSON.parse(read('la-telarana/progreso-fuentes.json'));
const row=feed.sourceCatalog.entries.find(e=>e.order===49);
assert.equal(f.metadata.reviewComplete,false);
assert.match(f.metadata.methodologicalNote,/sin prueba de identidad/);
assert.equal(f.metadata.identityWithOriginalConfirmed,false);
assert.equal(row.analysisCoverage.percent,0);
assert.equal(row.status,'pendiente');
assert.equal(row.tracking.initiated,false);
assert.equal(row.supplementalResearch.identityWithOriginalConfirmed,false);
assert.equal(row.originalUrl,'');
assert.equal(row.sourceUrl,'');
assert.equal(f.nodes.length,19);assert.equal(f.edges.length,32);
const ids=new Set(f.nodes.map(n=>n.id)),edgeIds=new Set(f.edges.map(e=>e.id));
assert.equal(ids.size,f.nodes.length);assert.equal(edgeIds.size,f.edges.length);
assert(f.edges.every(e=>ids.has(e.a)&&ids.has(e.b)&&e.a!==e.b));
assert(f.nodes.every(n=>n.podcastNotes?.every(note=>note.timeSec===null)));
assert(f.nodes.some(n=>n.id==='f49-candidato'&&n.note.includes('no sabemos si coincide')));
assert(f.nodes.some(n=>n.id==='f49-pelasgos'&&n.note.includes('no aparece corroborada')));
assert(f.nodes.some(n=>n.id==='f49-inferencia-edad-piedra'&&n.note.includes('no prueba')));
assert(f.edges.find(e=>e.id==='f49-inferencia-ritual').claimStatus==='inferencia_no_sustentada');
assert(f.edges.find(e=>e.id==='f49-desglaciacion-mar').claimStatus==='coincidencia_geologica_no_identificacion');
assert(f.edges.find(e=>e.id==='f49-etimologia-pelasgos').claimStatus==='hipotesis_etimologica_sin_fuente');
assert(row.supplementalResearch.additionalChecks.length===6);
assert.equal(row.supplementalResearch.entitiesInCandidateModule,f.nodes.length);
assert.equal(row.supplementalResearch.relationsInCandidateModule,f.edges.length);
assert.equal(context.window.IdeaLabSourceFilters.sourceForModule({key:'IDEA_TELARANA_F49_CANDIDATE'}),'extra:f49-candidate');
assert(read('la-telarana/index.html').includes('fuente-49-candidato.js?v=20261116-review2'));
assert(read('.github/workflows/pages.yml').includes('cp la-telarana/fuente-49-candidato.js'));
const history=JSON.parse(read('linea-historia/estudios-telarana.json'));
assert(!history.items.some(e=>e.investigation?.sourceOrder===49),'No fechar el mito como hecho histórico');
console.log('OK: candidato F49 separado; 19 nodos, 32 relaciones, 6 contrastes, original 0 %');
