import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const read=p=>fs.readFileSync(p,'utf8'),ctx={window:{}};
vm.runInNewContext(read('la-telarana/fuente-57-historia-judia.js'),ctx);
const f=ctx.window.IDEA_TELARANA_F57_REVIEW,ids=new Set(f.nodes.map(n=>n.id));
assert.equal(f.metadata.reviewComplete,false);
assert.equal(f.metadata.audioVerified,false);
assert(f.nodes.flatMap(n=>n.podcastNotes).every(n=>n.timeSec===null));
assert(f.edges.every(e=>ids.has(e.a)&&ids.has(e.b)&&e.a!==e.b));
assert.match(f.nodes.find(n=>n.id==='f57-decreto1492').note,/no es la fecha de salida/);
assert.match(f.nodes.find(n=>n.id==='f57-mundo-islamico').note,/no puede afirmarse ausencia universal/);
assert.match(f.nodes.find(n=>n.id==='f57-economia').note,/no permite asignar atributos económicos/);
const event=JSON.parse(read('linea-historia/estudios-telarana.json')).items.find(x=>x.id==='study-f57-decreto-granada-1492');
assert.equal(event.investigation.date,'1492-03-31');
assert.match(event.investigation.methodologicalLimits,/no al momento de salida/);
assert(read('la-telarana/index.html').includes('fuente-57-historia-judia.js'));
assert(read('.github/workflows/pages.yml').includes('cp la-telarana/fuente-57-historia-judia.js'));
console.log('OK: F57 distingue tradiciones, diversidad y decreto de 1492');
