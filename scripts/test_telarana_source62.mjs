import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const read=p=>fs.readFileSync(p,'utf8'),ctx={window:{}};
vm.runInNewContext(read('la-telarana/fuente-62-conflicto.js'),ctx);
const f=ctx.window.IDEA_TELARANA_F62_REVIEW,ids=new Set(f.nodes.map(n=>n.id));
assert.equal(f.metadata.reviewComplete,false);
assert.equal(f.metadata.audioVerified,false);
assert(f.nodes.flatMap(n=>n.podcastNotes).every(n=>n.timeSec===null));
assert(f.edges.every(e=>ids.has(e.a)&&ids.has(e.b)&&e.a!==e.b));
assert.match(f.nodes.find(n=>n.id==='f56-1967').note,/operaciones preventivas israelíes/);
assert.match(f.nodes.find(n=>n.id==='f62-observador').note,/puede cambiar/);
assert.match(f.nodes.find(n=>n.id==='f62-hamas').note,/no equivale/);
const items=JSON.parse(read('linea-historia/estudios-telarana.json')).items;
assert.equal(items.find(x=>x.id==='study-f62-june-war-1967').investigation.date,'1967-06-05');
assert.equal(items.find(x=>x.id==='study-f62-palestine-observer-2012').investigation.date,'2012-11-29');
assert(read('la-telarana/index.html').includes('fuente-62-conflicto.js'));
assert(read('.github/workflows/pages.yml').includes('cp la-telarana/fuente-62-conflicto.js'));
console.log('OK: F62 contrasta fechas y distingue población de grupos armados');
