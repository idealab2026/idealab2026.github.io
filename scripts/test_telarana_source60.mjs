import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const read=p=>fs.readFileSync(p,'utf8'),ctx={window:{}};
vm.runInNewContext(read('la-telarana/fuente-60-conflicto.js'),ctx);
const f=ctx.window.IDEA_TELARANA_F60_REVIEW,ids=new Set(f.nodes.map(n=>n.id));
assert.equal(f.metadata.reviewComplete,false);
assert.equal(f.metadata.audioVerified,false);
assert(f.nodes.flatMap(n=>n.podcastNotes).every(n=>n.timeSec===null));
assert(f.edges.every(e=>ids.has(e.a)&&ids.has(e.b)&&e.a!==e.b));
assert.match(f.nodes.find(n=>n.id==='f60-balfour').note,/No estableció por sí misma un Estado/);
assert.match(f.nodes.find(n=>n.id==='f60-oslo').note,/mayo de 1994/);
assert.match(f.nodes.find(n=>n.id==='f60-jerico').note,/no se infieren/);
const event=JSON.parse(read('linea-historia/estudios-telarana.json')).items.find(x=>x.id==='study-f60-balfour-1917');
assert.equal(event.investigation.date,'1917-11-02');
assert.match(event.investigation.methodologicalLimits,/no la creación de un Estado/);
assert(read('la-telarana/index.html').includes('fuente-60-conflicto.js'));
assert(read('.github/workflows/pages.yml').includes('cp la-telarana/fuente-60-conflicto.js'));
console.log('OK: F60 distingue documentos, períodos y testimonios');
