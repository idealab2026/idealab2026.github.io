/* Fuente 15: control de procedencia de PDF oficial, no es entrevista ni transcripción. */
import assert from "node:assert/strict";
import fs from "node:fs";
import vm from "node:vm";
const read=p=>fs.readFileSync(p,"utf8");
const source=read("la-telarana/fuente-15-estrategia-seguridad-2025.js");
const window={};
vm.runInNewContext(source,{window});
const item=window.IDEA_TELARANA_F15_PRIMARY;
assert(item?.metadata?.sourceOrder===15,"Falta F15 en la fuente documental");
assert(item.metadata.sourceType==="official_pdf","Se ha tratado PDF como podcast");
assert(item.metadata.transcriptRequired===false,"No requiere transcripción audiovisual");
assert(item.metadata.identicalBinaryToNotebookUploadVerified!==true,"No está verificada la identidad del binario");
assert(/^https:\/\/www\.whitehouse\.gov\//.test(item.metadata.url),"El original no procede de la Casa Blanca");
assert(item.nodes.length>=8&&item.edges.length>=7,"Documento no desarrollado");
const ids=new Set(item.nodes.map(n=>n.id));
assert(item.edges.every(x=>ids.has(x.a)&&ids.has(x.b)),"Vínculos sin nodos");
assert(item.edges.every(x=>/declaracion_institucional/.test(x.claimStatus)),"Los planes no son resultados demostrados");
const html=read("la-telarana/index.html"),workflow=read(".github/workflows/pages.yml");
assert(html.includes('src="./fuente-15-estrategia-seguridad-2025.js'),"Falta cargar el archivo");
assert(html.includes('"key":"IDEA_TELARANA_F15_PRIMARY"'),"Falta registro del documento");
assert(workflow.includes("cp la-telarana/fuente-15-estrategia-seguridad-2025.js dist/la-telarana/fuente-15-estrategia-seguridad-2025.js"),"No se publica el módulo");
const t=JSON.parse(read("la-telarana/progreso-fuentes.json"));
assert(t.inReview.some(e=>e.order===15&&!e.reviewComplete&&e.sourceType==="pdf_document"),"F15 debe seguir en revisión");
assert(t.counts.reviewedPublished+t.counts.inReview+t.counts.notStarted===t.total,"No cuadran fuentes");
const feed=JSON.parse(read("linea-historia/estudios-telarana.json"));
const h=feed.items.find(e=>e.id==="study-f15-nss-transmision-congreso-2025");
assert(h?.investigation?.date==="2025-12-02","Falta la transmisión documentada");
assert(h.investigation.sourceType==="pdf_document","Debe figurar fuente documental");
console.log("OK: F15 PDF institucional; "+item.nodes.length+" nodos, "+item.edges.length+" menciones y 1 hito registrado");
