import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const read=p=>fs.readFileSync(p,'utf8'),ctx={window:{}};
vm.runInNewContext(read('la-telarana/fuente-56-identidades.js'),ctx);
const f=ctx.window.IDEA_TELARANA_F56_REVIEW, ids=new Set(f.nodes.map(n=>n.id));
assert.equal(f.metadata.reviewComplete,false);
assert.equal(f.metadata.audioVerified,false);
assert(f.nodes.flatMap(n=>n.podcastNotes).every(n=>n.timeSec===null));
assert(f.edges.every(e=>ids.has(e.a)&&ids.has(e.b)&&e.a!==e.b));
assert.match(f.nodes.find(n=>n.id==='f56-palestinos').note,/derecho a la autodeterminación/);
assert.match(f.nodes.find(n=>n.id==='f56-judios').note,/no implica una postura política única/);
assert.match(f.nodes.find(n=>n.id==='f56-diversidad').note,/no es correcta/);
assert.match(f.nodes.find(n=>n.id==='f56-antisemitismo').note,/prejuicio u odio/);
const event=JSON.parse(read('linea-historia/estudios-telarana.json')).items.find(x=>x.id==='study-f56-uno-partition-1947');
assert.equal(event.investigation.date,'1947-11-29');
assert.match(event.investigation.methodologicalLimits,/rechazado/);
assert(read('la-telarana/index.html').includes('fuente-56-identidades.js'));
assert(read('.github/workflows/pages.yml').includes('cp la-telarana/fuente-56-identidades.js'));
console.log('OK: F56 distingue comunidades, evidencias históricas y generalizaciones');
